let lang = 'en';

export const currentLanguage = () => lang;
export const promptLanguage = (code = lang) => PROMPT_NAME[code] ?? PROMPT_NAME.en;
export const textDirection = (code = lang) => (RTL.has(code) ? 'rtl' : 'ltr');

// t('readerLoadingPart', { n: 3, total: 9 }) -> "Document context is loading (part 3 of 9)…" in the current language (English if missing).
export function t(key, vars = {}) {
  const text = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

// Follows the stored setting in any extension context (also the service worker, for its
// messages). onChange(lang) runs after the setting is known and after every change.
export function watchLanguage(onChange = () => {}) {
  const use = (value) => {
    lang = value in STRINGS ? value : 'en';
    onChange(lang);
  };
  chrome.storage.sync.get('lang').then((s) => use(s.lang), () => use('en'));
  chrome.storage.onChanged.addListener((changes, area) => area === 'sync' && changes.lang && use(changes.lang.newValue));
}

// Pages: translates the marked static texts, sets up the language switches, and calls
// onChange(lang) so the page can redraw its dynamic texts.
export function initI18n(onChange = () => {}) {
  for (const button of document.querySelectorAll('[data-lang-switch]')) setUpSwitch(button);
  watchLanguage((value) => {
    applyStatic();
    onChange(value);
  });
}

function applyStatic() {
  document.documentElement.lang = lang;
  for (const el of document.querySelectorAll('[data-i18n-dir]')) el.dir = textDirection();
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml); // strings from this file only
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of document.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.ariaLabel = t(el.dataset.i18nAria);
  for (const button of document.querySelectorAll('[data-lang-switch]')) {
    button.textContent = lang.toUpperCase();
    button.title = button.ariaLabel = `${t('language')}: ${LANGUAGES[lang]}`;
  }
  for (const item of document.querySelectorAll('.lang-menu [data-lang]')) item.ariaChecked = String(item.dataset.lang === lang);
}

// The button shows the current language code; a click opens the list of languages.
function setUpSwitch(button) {
  const wrap = document.createElement('span');
  wrap.className = 'lang-wrap';
  const menu = document.createElement('div');
  menu.className = 'lang-menu';
  menu.role = 'menu';
  menu.hidden = true;
  for (const [code, name] of Object.entries(LANGUAGES)) {
    const item = document.createElement('button');
    item.type = 'button';
    item.role = 'menuitemradio';
    item.dataset.lang = code;
    item.lang = code;
    item.dir = textDirection(code);
    item.append(Object.assign(document.createElement('span'), { className: 'code', textContent: code.toUpperCase() }), ` ${name}`);
    item.addEventListener('click', () => {
      chrome.storage.sync.set({ lang: code });
      show(false);
      button.focus();
    });
    menu.append(item);
  }
  button.replaceWith(wrap);
  wrap.append(button, menu);
  button.ariaHasPopup = 'menu';
  button.ariaExpanded = 'false';
  button.textContent = lang.toUpperCase();

  const show = (open) => {
    menu.hidden = !open;
    button.ariaExpanded = String(open);
    if (open) menu.querySelector(`[data-lang="${lang}"]`)?.focus();
  };
  button.addEventListener('click', () => show(menu.hidden));
  document.addEventListener('click', (e) => !wrap.contains(e.target) && show(false));
  wrap.addEventListener('keydown', (e) => {
    if (menu.hidden) return;
    const items = [...menu.children];
    const i = items.indexOf(document.activeElement);
    if (e.key === 'Escape') {
      show(false);
      button.focus();
    } else if (e.key === 'ArrowDown' || e.key === 'ArrowUp') {
      e.preventDefault();
      items[(i + (e.key === 'ArrowDown' ? 1 : items.length - 1)) % items.length].focus();
    }
  });
}
